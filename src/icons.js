const PATHS = {};
for (const [name, rows] of Object.entries(GRIDS)) {
  let d = '';
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x += 1; continue; }
      let end = x;
      while (row[end] === '#') end += 1;
      d += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  PATHS[name] = d;
}

const CATEGORY_ICON = { food: 'food', groceries: 'groceries', outings: 'outings', travel: 'travel', home: 'homeCat', other: 'other' };

function snap(size) {
  if (size <= 16) return 12;
  if (size <= 30) return 24;
  return 36;
}

export function Icon({ name, size = 24, label, class: cls = '' }) {
  const px = snap(size);
  return html`<svg class=${`icon ${cls}`} width=${px} height=${px} viewBox="0 0 12 12" fill="currentColor"
    shape-rendering="crispEdges" aria-hidden=${label ? undefined : 'true'} role=${label ? 'img' : undefined}
    aria-label=${label}><path d=${PATHS[name] ?? PATHS.other}/></svg>`;
}

export function categoryIcon(category) {
  return CATEGORY_ICON[category] ?? 'jar';
}
